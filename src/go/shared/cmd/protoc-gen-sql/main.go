package main

import (
	"fmt"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/pluginpb"

	sqlpb "quadsmith/shared/gen/quadsmith/sql"
)

func main() {
	protogen.Options{}.Run(func(gen *protogen.Plugin) error {
		gen.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)

		type dbOutput struct {
			file            *protogen.GeneratedFile
			alterStatements []string
		}
		outputs := make(map[string]*dbOutput)

		getOutput := func(dbName string) *dbOutput {
			if out, ok := outputs[dbName]; ok {
				return out
			}
			g := gen.NewGeneratedFile(dbName+".sql", "")
			g.P("-- Code generated by protoc-gen-sql. DO NOT EDIT.")
			g.P()
			out := &dbOutput{file: g}
			outputs[dbName] = out
			return out
		}

		processFile := func(f *protogen.File) {
			if !f.Generate {
				return
			}

			pkg := string(f.Desc.Package())
			dbName := strings.ReplaceAll(pkg, ".", "_")
			if strings.HasSuffix(f.Proto.GetName(), "store/ops.proto") || pkg == "quadsmith.ops" {
				dbName = "quadsmith_ops"
			} else if pkg == "quadsmith.store" || pkg == "quadsmith.api" {
				dbName = "quadsmith_api"
			} else if dbName == "" {
				dbName = "quadsmith"
			}

			for _, msg := range f.Messages {
				if getTableOptions(msg) == nil {
					continue
				}
				out := getOutput(dbName)
				alters := generateTable(out.file, msg)
				out.alterStatements = append(out.alterStatements, alters...)
			}
		}

		// Emit quadsmith.store base tables before quadsmith.api child tables.
		for _, f := range gen.Files {
			if string(f.Desc.Package()) == "quadsmith.store" {
				processFile(f)
			}
		}
		for _, f := range gen.Files {
			if string(f.Desc.Package()) != "quadsmith.store" {
				processFile(f)
			}
		}

		for _, out := range outputs {
			if len(out.alterStatements) > 0 {
				out.file.P("-- Foreign Keys")
				for _, stmt := range out.alterStatements {
					out.file.P(stmt)
				}
			}
		}

		return nil
	})
}

var entityInheritedFields = map[string]bool{
	"id":                    true,
	"name":                  true,
	"description":           true,
	"reference_links":       true,
	"primary_display_image": true,
	"media":                 true,
	"user_uuid":             true,
	"author_username":       true,
}

func isInheritedField(tblOpts *sqlpb.TableOptions, fieldName string) bool {
	return tblOpts != nil && tblOpts.GetInherits() == "entities" && entityInheritedFields[fieldName]
}

func getTableOptions(msg *protogen.Message) *sqlpb.TableOptions {
	opts := msg.Desc.Options()
	if proto.HasExtension(opts, sqlpb.E_Table) {
		if tblOpts, ok := proto.GetExtension(opts, sqlpb.E_Table).(*sqlpb.TableOptions); ok && tblOpts != nil && tblOpts.Name != "" {
			return tblOpts
		}
	}
	return nil
}

func generateTable(g *protogen.GeneratedFile, msg *protogen.Message) []string {
	tblOpts := getTableOptions(msg)
	if tblOpts == nil {
		return nil
	}
	tableName := tblOpts.Name

	g.P("CREATE TABLE IF NOT EXISTS ", tableName, " (")

	var defs []string
	var alters []string

	for _, field := range msg.Fields {
		if isInheritedField(tblOpts, string(field.Desc.Name())) {
			continue
		}

		fOpts := field.Desc.Options()

		var colOpt *sqlpb.ColumnOptions
		if proto.HasExtension(fOpts, sqlpb.E_Column) {
			if co, ok := proto.GetExtension(fOpts, sqlpb.E_Column).(*sqlpb.ColumnOptions); ok && co != nil {
				colOpt = co
			}
		}

		colName := string(field.Desc.Name())
		if colOpt != nil && colOpt.Name != "" {
			colName = colOpt.Name
		}
		colType := ""
		if colOpt != nil && colOpt.ColumnType != "" {
			colType = colOpt.ColumnType
		} else {
			colType = sqlDataType(field.Desc)
		}

		if colOpt != nil && colOpt.IsUnique {
			colType += " UNIQUE"
		}

		if colOpt != nil && colOpt.DefaultValue != "" {
			colType += " DEFAULT " + colOpt.DefaultValue
		}

		if !field.Desc.IsList() && !field.Desc.HasPresence() {
			colType += " NOT NULL"
		}

		defs = append(defs, fmt.Sprintf("%s %s", colName, colType))

		// Check primary key
		if colOpt != nil && colOpt.IsPrimaryKey {
			defs = append(defs, fmt.Sprintf("PRIMARY KEY (%s)", colName))
		}

		// Check foreign key
		if colOpt != nil && colOpt.References != "" {
			alters = append(alters, fmt.Sprintf("ALTER TABLE %s ADD CONSTRAINT fk_%s_%s FOREIGN KEY (%s) REFERENCES %s;", tableName, tableName, colName, colName, colOpt.References))
		}
	}

	for _, chk := range tblOpts.GetChecks() {
		defs = append(defs, fmt.Sprintf("CHECK (%s)", chk))
	}

	for _, uq := range tblOpts.GetUniqueConstraints() {
		cleanUq := strings.ReplaceAll(strings.ReplaceAll(uq, ", ", "_"), ",", "_")
		cName := fmt.Sprintf("%s_%s_key", tableName, cleanUq)
		if len(cName) > 63 {
			cName = cName[:63]
		}
		defs = append(defs, fmt.Sprintf("CONSTRAINT %s UNIQUE (%s)", cName, uq))
	}

	g.P("    ", strings.Join(defs, ",\n    "))
	g.P(");")
	g.P()

	// Generate indexes
	for _, field := range msg.Fields {
		if isInheritedField(tblOpts, string(field.Desc.Name())) {
			continue
		}
		fOpts := field.Desc.Options()
		if proto.HasExtension(fOpts, sqlpb.E_Column) {
			if co, ok := proto.GetExtension(fOpts, sqlpb.E_Column).(*sqlpb.ColumnOptions); ok && co != nil && co.CreateIndex {
				colName := string(field.Desc.Name())
				if co.Name != "" {
					colName = co.Name
				}
				g.P("CREATE INDEX IF NOT EXISTS idx_", tableName, "_", colName, " ON ", tableName, " (", colName, ");")
			}
		}
	}

	// Generate custom/partial unique indexes
	for _, uidx := range tblOpts.GetUniqueIndexes() {
		if uidx.GetName() != "" && uidx.GetColumns() != "" {
			stmt := fmt.Sprintf("CREATE UNIQUE INDEX IF NOT EXISTS %s ON %s (%s)", uidx.GetName(), tableName, uidx.GetColumns())
			if uidx.GetWhere() != "" {
				stmt += fmt.Sprintf(" WHERE %s", uidx.GetWhere())
			}
			stmt += ";"
			g.P(stmt)
		}
	}
	g.P()
	return alters
}

func sqlDataType(desc protoreflect.FieldDescriptor) string {
	name := string(desc.Name())
	kind := desc.Kind()

	if desc.IsList() {
		if kind == protoreflect.StringKind {
			if strings.HasSuffix(name, "uuids") {
				return "UUID[]"
			}
			return "TEXT[]"
		}
		if kind == protoreflect.MessageKind {
			return "JSONB"
		}
	}

	if strings.HasSuffix(name, "uuid") && kind == protoreflect.StringKind {
		return "UUID"
	}
	switch kind {
	case protoreflect.MessageKind:
		if desc.Message() != nil && desc.Message().FullName() == "google.protobuf.Timestamp" {
			return "TIMESTAMPTZ"
		}
		return "JSONB"
	case protoreflect.StringKind:
		return "TEXT"
	case protoreflect.Int32Kind, protoreflect.Uint32Kind, protoreflect.EnumKind:
		return "INTEGER"
	case protoreflect.Int64Kind, protoreflect.Uint64Kind:
		return "BIGINT"
	case protoreflect.FloatKind, protoreflect.DoubleKind:
		return "DECIMAL"
	case protoreflect.BoolKind:
		return "BOOLEAN"
	default:
		return "TEXT"
	}
}
