type CatalogDomain struct {
	Message proto.Message
	Aliases []string
}

func (d CatalogDomain) MessageName() string {
	return string(d.Message.ProtoReflect().Descriptor().Name())
}

func (d CatalogDomain) PluralName() string {
	name := d.MessageName()
	if strings.HasSuffix(name, "y") {
		return strings.TrimSuffix(name, "y") + "ies"
	}
	if strings.HasSuffix(name, "s") {
		return name
	}
	return name + "s"
}

func (d CatalogDomain) Path() string {
	opts := d.Message.ProtoReflect().Descriptor().Options()
	if proto.HasExtension(opts, common.E_CollectionPath) {
		if p, ok := proto.GetExtension(opts, common.E_CollectionPath).(string); ok && p != "" {
			return strings.Trim(p, "/")
		}
	}
	return "components/" + strings.ToLower(d.PluralName())
}

func (d CatalogDomain) CLI() string {
	parts := strings.Split(d.Path(), "/")
	return parts[len(parts)-1]
}

func (d CatalogDomain) Category() string {
	parts := strings.Split(d.Path(), "/")
	if len(parts) >= 3 {
		return parts[1]
	}
	return "hardware"
}

func (d CatalogDomain) VarPrefix() string {
	name := d.MessageName()
	return strings.ToLower(name[:1]) + name[1:]
}

