package main

import (
	"fmt"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/pluginpb"

	commonpb "quadsmith/shared/gen/quadsmith/common"
	sqlpb "quadsmith/shared/gen/quadsmith/sql"
)

func main() {
	protogen.Options{}.Run(func(gen *protogen.Plugin) error {
		gen.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)
		for _, f := range gen.Files {
			if !f.Generate {
				continue
			}
			generateFile(gen, f)
		}
		return nil
	})
}

func getTableName(msg *protogen.Message) string {
	opts := msg.Desc.Options()
	if proto.HasExtension(opts, sqlpb.E_Table) {
		if tblOpts, ok := proto.GetExtension(opts, sqlpb.E_Table).(*sqlpb.TableOptions); ok && tblOpts != nil && tblOpts.Name != "" {
			return tblOpts.Name
		}
	}
	return ""
}

func getCollectionPath(msg *protogen.Message) string {
	opts := msg.Desc.Options()
	if proto.HasExtension(opts, commonpb.E_CollectionPath) {
		if p, ok := proto.GetExtension(opts, commonpb.E_CollectionPath).(string); ok && p != "" {
			return strings.Trim(p, "/")
		}
	}
	return ""
}

func generateFile(gen *protogen.Plugin, file *protogen.File) {
	hasTables := false
	for _, msg := range file.Messages {
		if getTableName(msg) != "" {
			hasTables = true
			break
		}
	}
	if !hasTables {
		return
	}

	filename := file.GeneratedFilenamePrefix + "_store.pb.go"
	g := gen.NewGeneratedFile(filename, file.GoImportPath)

	hasTimestamp := false
	for _, msg := range file.Messages {
		if getTableName(msg) == "" {
			continue
		}
		for _, f := range msg.Fields {
			if isTimestampField(f) {
				hasTimestamp = true
				break
			}
		}
		if hasTimestamp {
			break
		}
	}

	g.P("// Code generated by protoc-gen-store. DO NOT EDIT.")
	g.P("package ", file.GoPackageName)
	g.P()
	g.P(`import (`)
	g.P(`	"context"`)
	g.P(`	"fmt"`)
	g.P(`	"strings"`)
	if hasTimestamp {
		g.P(`	"time"`)
	}
	g.P(`	"github.com/jackc/pgx/v5"`)
	g.P(`	"github.com/jackc/pgx/v5/pgxpool"`)
	if hasTimestamp {
		g.P(`	"google.golang.org/protobuf/types/known/timestamppb"`)
	}
	g.P(`	"quadsmith/shared/pkg/pagination"`)
	g.P(`)`)
	g.P()

	for _, msg := range file.Messages {
		generateStoreForMessage(g, msg)
	}
}

func isTimestampField(field *protogen.Field) bool {
	return field.Desc.Kind() == protoreflect.MessageKind &&
		field.Desc.Message() != nil &&
		field.Desc.Message().FullName() == "google.protobuf.Timestamp"
}

func generateStoreForMessage(g *protogen.GeneratedFile, msg *protogen.Message) {
	tableName := getTableName(msg)
	if tableName == "" {
		return
	}

	msgName := msg.GoIdent.GoName
	collPath := getCollectionPath(msg)
	hasEntitiesJoin := collPath != "" && tableName != "entities"

	collName := ""
	if hasEntitiesJoin {
		parts := strings.Split(collPath, "/")
		collName = parts[len(parts)-1]
	}

	// activeFields: fields stored directly in tableName (for INSERT/UPDATE)
	var activeFields []*protogen.Field
	for _, field := range msg.Fields {
		var colOpt *sqlpb.ColumnOptions
		if proto.HasExtension(field.Desc.Options(), sqlpb.E_Column) {
			if co, ok := proto.GetExtension(field.Desc.Options(), sqlpb.E_Column).(*sqlpb.ColumnOptions); ok && co != nil {
				colOpt = co
			}
		}
		if colOpt != nil && colOpt.Ignore {
			continue
		}
		activeFields = append(activeFields, field)
	}

	// readableFields: fields accessible for SELECT (Get and List)
	var readableFields []*protogen.Field
	if hasEntitiesJoin {
		readableFields = msg.Fields
	} else {
		readableFields = activeFields
	}

	var activeColNames []string
	var placeHolders []string
	var mFields []string
	for i, field := range activeFields {
		colName := string(field.Desc.Name())
		colType := ""
		if proto.HasExtension(field.Desc.Options(), sqlpb.E_Column) {
			if co, ok := proto.GetExtension(field.Desc.Options(), sqlpb.E_Column).(*sqlpb.ColumnOptions); ok && co != nil {
				if co.Name != "" {
					colName = co.Name
				}
				if co.ColumnType != "" {
					colType = co.ColumnType
				}
			}
		}
		activeColNames = append(activeColNames, colName)

		if colType != "" {
			placeHolders = append(placeHolders, fmt.Sprintf("$%d::%s", i+1, colType))
		} else {
			placeHolders = append(placeHolders, fmt.Sprintf("$%d", i+1))
		}

		goName := field.GoName
		if isTimestampField(field) {
			mFields = append(mFields, "func(ts *timestamppb.Timestamp) interface{} { if ts == nil { return nil }; return ts.AsTime() }(m."+goName+")")
		} else if strings.HasSuffix(colName, "uuid") {
			if field.Desc.HasPresence() {
				mFields = append(mFields, "func(s *string) interface{} { if s == nil || *s == \"\" { return nil }; return *s }(m."+goName+")")
			} else {
				mFields = append(mFields, "func(s string) interface{} { if s == \"\" { return nil }; return s }(m."+goName+")")
			}
		} else if strings.HasSuffix(colName, "uuids") {
			mFields = append(mFields, "func(s []string) interface{} { if len(s) == 0 { return nil }; return s }(m."+goName+")")
		} else {
			mFields = append(mFields, "m."+goName)
		}
	}

	colsStr := strings.Join(activeColNames, ", ")
	valsStr := strings.Join(placeHolders, ", ")
	mFieldsStr := strings.Join(mFields, ", ")

	// --- CREATE ---
	g.P("func Create", msgName, "(ctx context.Context, tx pgx.Tx, m *", msgName, ") error {")
	g.P("	query := `INSERT INTO ", tableName, " (", colsStr, ") VALUES (", valsStr, ")`")
	g.P("	_, err := tx.Exec(ctx, query, ", mFieldsStr, ")")
	g.P("	return err")
	g.P("}")
	g.P()

	// readable columns
	var readableColNames []string
	for _, field := range readableFields {
		colName := string(field.Desc.Name())
		if proto.HasExtension(field.Desc.Options(), sqlpb.E_Column) {
			if co, ok := proto.GetExtension(field.Desc.Options(), sqlpb.E_Column).(*sqlpb.ColumnOptions); ok && co != nil {
				if co.Name != "" {
					colName = co.Name
				}
			}
		}
		readableColNames = append(readableColNames, colName)
	}

	readableColsStr := strings.Join(readableColNames, ", ")
	validColsStr := "map[string]bool{\"" + strings.Join(readableColNames, "\": true, \"") + "\": true}"

	hasId := false
	for _, col := range readableColNames {
		if col == "id" {
			hasId = true
			break
		}
	}

	getWhereClause := "uuid::text = $1"
	if hasEntitiesJoin {
		getWhereClause = "entities.id = $1 OR entities.uuid::text = $1"
	} else if hasId {
		getWhereClause = "id = $1 OR uuid::text = $1"
	}

	fromClause := tableName
	if hasEntitiesJoin {
		fromClause = tableName + " INNER JOIN entities USING (uuid)"
	}

	// --- GET ---
	g.P("func Get", msgName, "(ctx context.Context, db *pgxpool.Pool, idOrUuid string, cols []string) (*", msgName, ", error) {")
	g.P("	validCols := " + validColsStr)
	g.P("	colsStr := \"", readableColsStr, "\"")
	g.P("	if len(cols) > 0 {")
	g.P("		safeCols := make([]string, 0, len(cols))")
	g.P("		for _, col := range cols {")
	g.P("			if !validCols[col] {")
	g.P("				return nil, pagination.ErrInvalidColumn(col)")
	g.P("			}")
	g.P("			safeCols = append(safeCols, pgx.Identifier{col}.Sanitize())")
	g.P("		}")
	g.P("		colsStr = strings.Join(safeCols, \", \")")
	g.P("	} else {")
	g.P("       cols = []string{\"" + strings.ReplaceAll(readableColsStr, ", ", "\", \"") + "\"}")
	g.P("   }")
	g.P("	query := `SELECT ` + colsStr + ` FROM ", fromClause, " WHERE ", getWhereClause, " LIMIT 1`")
	g.P("	scanArgs := make([]interface{}, len(cols))")
	g.P("	scanAssigns := make([]func(), 0, len(cols))")
	g.P("	m := &", msgName, "{}")
	g.P("	for i, col := range cols {")
	g.P("		switch col {")
	for j, colName := range readableColNames {
		field := readableFields[j]
		goName := field.GoName
		g.P("		case \"", colName, "\":")
		if isTimestampField(field) {
			g.P("			var v *time.Time")
			g.P("			scanArgs[i] = &v")
			g.P("			scanAssigns = append(scanAssigns, func() {")
			g.P("				if v != nil {")
			g.P("					m.", goName, " = timestamppb.New(*v)")
			g.P("				}")
			g.P("			})")
		} else if field.Desc.HasPresence() {
			g.P("			scanArgs[i] = &m.", goName)
		} else if strings.HasSuffix(colName, "uuid") && colName != "uuid" && !field.Desc.IsList() {
			g.P("			var v *string")
			g.P("			scanArgs[i] = &v")
			g.P("			scanAssigns = append(scanAssigns, func() {")
			g.P("				if v != nil {")
			g.P("					m.", goName, " = *v")
			g.P("				}")
			g.P("			})")
		} else {
			g.P("			scanArgs[i] = &m.", goName)
		}
	}
	g.P("		default:")
	g.P("			var dummy interface{}")
	g.P("			scanArgs[i] = &dummy")
	g.P("		}")
	g.P("	}")
	g.P()
	g.P("	err := db.QueryRow(ctx, query, idOrUuid).Scan(scanArgs...)")
	g.P("	if err != nil {")
	g.P("		return nil, err")
	g.P("	}")
	g.P("	for _, assign := range scanAssigns {")
	g.P("		assign()")
	g.P("	}")
	g.P("	return m, nil")
	g.P("}")
	g.P()

	// --- UPDATE ---
	var updateSets []string
	var updateArgs []string
	updateArgs = append(updateArgs, "m.Uuid")

	argIdx := 2
	for i, field := range activeFields {
		colName := activeColNames[i]
		colType := ""
		if proto.HasExtension(field.Desc.Options(), sqlpb.E_Column) {
			if co, ok := proto.GetExtension(field.Desc.Options(), sqlpb.E_Column).(*sqlpb.ColumnOptions); ok && co != nil {
				if co.ColumnType != "" {
					colType = co.ColumnType
				}
			}
		}

		if colName == "uuid" || colName == "id" {
			continue
		}

		if colType != "" {
			updateSets = append(updateSets, fmt.Sprintf("%s = $%d::%s", colName, argIdx, colType))
		} else {
			updateSets = append(updateSets, fmt.Sprintf("%s = $%d", colName, argIdx))
		}

		updateArgs = append(updateArgs, mFields[i])
		argIdx++
	}

	updateSetsStr := strings.Join(updateSets, ", ")
	updateArgsStr := strings.Join(updateArgs, ", ")

	g.P("func Update", msgName, "(ctx context.Context, tx pgx.Tx, m *", msgName, ") error {")
	if len(updateSets) > 0 {
		g.P("	query := `UPDATE ", tableName, " SET ", updateSetsStr, " WHERE uuid = $1`")
		g.P("	_, err := tx.Exec(ctx, query, ", updateArgsStr, ")")
		g.P("	return err")
	} else {
		g.P("	return nil")
	}
	g.P("}")
	g.P()

	// --- DELETE ---
	deleteWhere := "uuid::text = $1"
	if hasEntitiesJoin {
		deleteWhere = "uuid = (SELECT uuid FROM entities WHERE (id = $1 OR uuid::text = $1) AND collection = '" + collName + "' LIMIT 1) OR uuid::text = $1"
	} else if hasId {
		deleteWhere = "id = $1 OR uuid::text = $1"
	}
	g.P("func Delete", msgName, "(ctx context.Context, tx pgx.Tx, idOrUuid string) error {")
	g.P("	query := `DELETE FROM ", tableName, " WHERE ", deleteWhere, "`")
	g.P("	_, err := tx.Exec(ctx, query, idOrUuid)")
	g.P("	return err")
	g.P("}")
	g.P()

	// --- LIST ---
	pluralName := msgName + "s"
	if strings.HasSuffix(msgName, "y") {
		pluralName = strings.TrimSuffix(msgName, "y") + "ies"
	} else if strings.HasSuffix(msgName, "s") {
		pluralName = msgName
	}

	g.P("func List", pluralName, "(ctx context.Context, db *pgxpool.Pool, cols []string, sorts []string, whereClause string, limit int32, offset int32, args ...any) ([]*", msgName, ", error) {")
	g.P("	validCols := " + validColsStr)
	g.P("	colsStr := \"", readableColsStr, "\"")
	g.P("	if len(cols) > 0 {")
	g.P("		safeCols := make([]string, 0, len(cols))")
	g.P("		for _, col := range cols {")
	g.P("			if !validCols[col] {")
	g.P("				return nil, pagination.ErrInvalidColumn(col)")
	g.P("			}")
	g.P("			safeCols = append(safeCols, pgx.Identifier{col}.Sanitize())")
	g.P("		}")
	g.P("		colsStr = strings.Join(safeCols, \", \")")
	g.P("	} else {")
	g.P("       cols = []string{\"" + strings.ReplaceAll(readableColsStr, ", ", "\", \"") + "\"}")
	g.P("   }")
	g.P("	query := `SELECT ` + colsStr + ` FROM ", fromClause, "`")
	if hasEntitiesJoin {
		g.P("	query += \" WHERE entities.is_archived = false\"")
		g.P("	if whereClause != \"\" {")
		g.P("		query += \" AND (\" + whereClause + \")\"")
		g.P("	}")
	} else {
		g.P("	if whereClause != \"\" {")
		g.P("		query += \" WHERE \" + whereClause")
		g.P("	}")
	}
	g.P("	var orderClauses []string")
	g.P("	hasIdSort := false")
	g.P("	if len(sorts) > 0 {")
	g.P("		for _, s := range sorts {")
	g.P("			col := s")
	g.P("			dir := \"ASC NULLS LAST\"")
	g.P("			if strings.HasPrefix(s, \"^\") {")
	g.P("				col = s[1:]")
	g.P("				dir = \"DESC NULLS LAST\"")
	g.P("			}")
	g.P("			if !validCols[col] {")
	g.P("				return nil, pagination.ErrInvalidSortColumn(col)")
	g.P("			}")
	g.P("			if col == \"id\" || col == \"uuid\" {")
	g.P("				hasIdSort = true")
	g.P("			}")
	g.P("			orderClauses = append(orderClauses, pgx.Identifier{col}.Sanitize() + \" \" + dir)")
	g.P("		}")
	g.P("	}")
	g.P("	if !hasIdSort {")
	if hasId || hasEntitiesJoin {
		g.P("		orderClauses = append(orderClauses, \"id ASC\")")
	} else {
		g.P("		orderClauses = append(orderClauses, \"uuid ASC\")")
	}
	g.P("	}")
	g.P("	query += \" ORDER BY \" + strings.Join(orderClauses, \", \")")
	g.P("	if limit > 0 {")
	g.P("		query += fmt.Sprintf(\" LIMIT $%d\", len(args)+1)")
	g.P("		args = append(args, limit)")
	g.P("	}")
	g.P("	if offset > 0 {")
	g.P("		query += fmt.Sprintf(\" OFFSET $%d\", len(args)+1)")
	g.P("		args = append(args, offset)")
	g.P("	}")
	g.P("	rows, err := db.Query(ctx, query, args...)")
	g.P("	if err != nil {")
	g.P("		return nil, err")
	g.P("	}")
	g.P("	defer rows.Close()")
	g.P("	results := make([]*", msgName, ", 0)")
	g.P("	for rows.Next() {")
	g.P("		scanArgs := make([]interface{}, len(cols))")
	g.P("		scanAssigns := make([]func(), 0, len(cols))")
	g.P("		m := &", msgName, "{}")
	g.P("		for i, col := range cols {")
	g.P("			switch col {")
	for j, colName := range readableColNames {
		field := readableFields[j]
		goName := field.GoName
		g.P("			case \"", colName, "\":")
		if isTimestampField(field) {
			g.P("				var v *time.Time")
			g.P("				scanArgs[i] = &v")
			g.P("				scanAssigns = append(scanAssigns, func() {")
			g.P("					if v != nil {")
			g.P("						m.", goName, " = timestamppb.New(*v)")
			g.P("					}")
			g.P("				})")
		} else if field.Desc.HasPresence() {
			g.P("				scanArgs[i] = &m.", goName)
		} else if strings.HasSuffix(colName, "uuid") && colName != "uuid" && !field.Desc.IsList() {
			g.P("				var v *string")
			g.P("				scanArgs[i] = &v")
			g.P("				scanAssigns = append(scanAssigns, func() {")
			g.P("					if v != nil {")
			g.P("						m.", goName, " = *v")
			g.P("					}")
			g.P("				})")
		} else {
			g.P("				scanArgs[i] = &m.", goName)
		}
	}
	g.P("			default:")
	g.P("				var dummy interface{}")
	g.P("				scanArgs[i] = &dummy")
	g.P("			}")
	g.P("		}")
	g.P("		err := rows.Scan(scanArgs...)")
	g.P("		if err != nil {")
	g.P("			return nil, err")
	g.P("		}")
	g.P("		for _, assign := range scanAssigns {")
	g.P("			assign()")
	g.P("		}")
	g.P("		results = append(results, m)")
	g.P("	}")
	g.P("	return results, nil")
	g.P("}")
	g.P()
}
