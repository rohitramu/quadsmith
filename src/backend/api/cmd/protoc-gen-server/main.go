func getCollectionPath(msg *protogen.Message) string {
	opts := msg.Desc.Options()
	if proto.HasExtension(opts, quadsmith_sql.E_CollectionPath) {
		if p, ok := proto.GetExtension(opts, quadsmith_sql.E_CollectionPath).(string); ok && p != "" {
			return strings.Trim(p, "/")
		}
	}
	return ""
}

