			g.P("	b := req.Msg.GetBuild()")
			g.P("	if b == nil {")
			g.P("		return nil, connect.NewError(connect.CodeInvalidArgument, errors.New(\"build object is required\"))")
			g.P("	}")
			g.P()
			g.P("	// 1. Assign UUID v7 if empty")
			g.P("	if b.Uuid == \"\" {")
			g.P("		var randBytes [16]byte")
			g.P("		if _, err := rand.Read(randBytes[:]); err != nil {")
			g.P("			return nil, connect.NewError(connect.CodeInternal, fmt.Errorf(\"failed to generate uuid: %w\", err))")
			g.P("		}")
			g.P("		ms := time.Now().UnixMilli()")
			g.P("		randBytes[0] = byte(ms >> 40)")
			g.P("		randBytes[1] = byte(ms >> 32)")
			g.P("		randBytes[2] = byte(ms >> 24)")
			g.P("		randBytes[3] = byte(ms >> 16)")
			g.P("		randBytes[4] = byte(ms >> 8)")
			g.P("		randBytes[5] = byte(ms)")
			g.P("		randBytes[6] = (randBytes[6] & 0x0f) | 0x70 // UUID v7")
			g.P("		randBytes[8] = (randBytes[8] & 0x3f) | 0x80 // RFC 4122")
			g.P("		b.Uuid = fmt.Sprintf(\"%08x-%04x-%04x-%04x-%012x\", randBytes[0:4], randBytes[4:6], randBytes[6:8], randBytes[8:10], randBytes[10:16])")
			g.P("	}")
			g.P()
			g.P("	// 2. Generate unique slug if empty")
			g.P("	if b.Id == \"\" {")
			g.P("		reg := regexp.MustCompile(\"[^a-z0-9]+\")")
			g.P("		slug := strings.Trim(reg.ReplaceAllString(strings.ToLower(b.Name), \"-\"), \"-\")")
			g.P("		if slug == \"\" {")
			g.P("			slug = \"build-\" + b.Uuid[:8]")
