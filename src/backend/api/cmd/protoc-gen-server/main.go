			g.P("			}")
			g.P("		}")
			g.P("	}")
			g.P("	for i, idOrUuid := range b.ReceiverUuids {")
			g.P("		if idOrUuid != \"\" {")
			g.P("			if m, err := GetReceiver(ctx, s.db, idOrUuid, []string{\"uuid\"}); err == nil && m != nil && m.Uuid != \"\" {")
			g.P("				b.ReceiverUuids[i] = m.Uuid")
			g.P("			}")
			g.P("		}")
			g.P("	}")
			g.P("	for i, idOrUuid := range b.AntennaUuids {")
			g.P("		if idOrUuid != \"\" {")
			g.P("			if m, err := GetAntenna(ctx, s.db, idOrUuid, []string{\"uuid\"}); err == nil && m != nil && m.Uuid != \"\" {")
