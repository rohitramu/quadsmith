			g.P("		b.Id = slug")
			g.P("	}")
			g.P()
			g.P("	// 3. Translate any foreign key human-readable IDs to UUIDs (per AGENTS.md rule)")
			g.P("	if b.FrameUuid != \"\" {")
			g.P("		if m, err := GetFrame(ctx, s.db, b.FrameUuid, []string{\"uuid\"}); err == nil && m != nil && m.Uuid != \"\" {")
			g.P("			b.FrameUuid = m.Uuid")
			g.P("		}")
			g.P("	}")
			g.P("	if b.MotorUuid != \"\" {")
			g.P("		if m, err := GetMotor(ctx, s.db, b.MotorUuid, []string{\"uuid\"}); err == nil && m != nil && m.Uuid != \"\" {")
			g.P("			b.MotorUuid = m.Uuid")
			g.P("		}")
			g.P("	}")
			g.P("	if b.PropellerUuid != \"\" {")
			g.P("		if m, err := GetPropeller(ctx, s.db, b.PropellerUuid, []string{\"uuid\"}); err == nil && m != nil && m.Uuid != \"\" {")
			g.P("			b.PropellerUuid = m.Uuid")
			g.P("		}")
			g.P("	}")
			g.P("	if b.FlightControllerUuid != \"\" {")
			g.P("		if m, err := GetFlightController(ctx, s.db, b.FlightControllerUuid, []string{\"uuid\"}); err == nil && m != nil && m.Uuid != \"\" {")
			g.P("			b.FlightControllerUuid = m.Uuid")
			g.P("		}")
			g.P("	}")
			g.P("	if b.VideoTransmitterUuid != \"\" {")
			g.P("		if m, err := GetVideoTransmitter(ctx, s.db, b.VideoTransmitterUuid, []string{\"uuid\"}); err == nil && m != nil && m.Uuid != \"\" {")
			g.P("			b.VideoTransmitterUuid = m.Uuid")
			g.P("		}")
			g.P("	}")
			g.P("	if b.GpsReceiverUuid != nil && *b.GpsReceiverUuid != \"\" {")
			g.P("		if m, err := GetGpsReceiver(ctx, s.db, *b.GpsReceiverUuid, []string{\"uuid\"}); err == nil && m != nil && m.Uuid != \"\" {")
			g.P("			*b.GpsReceiverUuid = m.Uuid")
