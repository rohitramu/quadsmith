		g.P("		return nil, connect.NewError(connect.CodeInternal, err)")
		g.P("	}")
		g.P()
		g.P("	nextPageToken := \"\"")
		g.P("	if int32(len(items)) > pageSize {")
		g.P("		items = items[:pageSize]")
